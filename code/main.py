"""Ghost Data Still Exists: deletion-audit agent. Run from the repo root:

    python3 code/main.py

Reads dataset/, answers every request in dataset/deletion_requests.csv and writes:
- output.csv at the repo root (checked against the format rules before it is saved);
- code/evaluation/warnings_report.md: cases and records a person should review;
- code/evaluation/run_record.md: how this output was made (data and code fingerprints, model,
  prompt versions, counts, AI usage), so the run can be reproduced and checked.

AI is used only for screenshots/PDFs and request texts, and its answers are saved in code/llm_cache.
Without LLM_API_KEY the agent uses those saved answers only and makes no AI call.

Options (for tests and evaluation): --dataset DIR, --requests CSV, --output CSV, --reports-dir DIR,
--no-ai (word check only, screenshots/PDFs unread).
"""
import argparse
import csv
import hashlib
import json
import os
import sys
import tempfile
from collections import Counter
from datetime import datetime, timezone

CODE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, CODE_DIR)

import validate_output  # noqa: E402
from audit import prompts  # noqa: E402
from audit.agent import Agent  # noqa: E402
from audit.llm import LLMClient, LLMError, Prompt  # noqa: E402
from audit.settings import DATASET_DIR, LLM_CACHE_DIR, REPO_ROOT, load_settings  # noqa: E402

HEADER = ["case_id", "deletion_status", "steps_json"]


def fingerprint_files(paths):
    digest = hashlib.sha256()
    for path in sorted(paths):
        digest.update(os.path.relpath(path, REPO_ROOT).encode("utf-8"))
        with open(path, "rb") as f:
            digest.update(f.read())
    return digest.hexdigest()


def files_under(folder, extensions=None):
    found = []
    for root, dirs, names in os.walk(folder):
        dirs[:] = [d for d in dirs if d not in ("__pycache__", "llm_cache", "tests")]
        found += [os.path.join(root, n) for n in names if extensions is None or n.endswith(extensions)]
    return found


def write_output(rows, path):
    """Write the CSV atomically: a half-written output.csv is never left behind."""
    folder = os.path.dirname(os.path.abspath(path))
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="", dir=folder, delete=False, suffix=".tmp") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(HEADER)
        for row in rows:
            writer.writerow(row)
        temp = f.name
    return temp


def ai_usage(client):
    if client is None:
        return {"live_calls": 0, "cache_hits": 0, "input_tokens": 0, "output_tokens": 0, "by_prompt": {}}
    by_prompt = {}
    for t in client.trace:
        p = by_prompt.setdefault(f"{t['prompt_id']} v{t['prompt_version']}",
                                 {"live_calls": 0, "cache_hits": 0, "input_tokens": 0, "output_tokens": 0})
        p["cache_hits" if t["cache_hit"] else "live_calls"] += 1
        p["input_tokens"] += t["input_tokens"]
        p["output_tokens"] += t["output_tokens"]
    total = {k: sum(p[k] for p in by_prompt.values()) for k in ("live_calls", "cache_hits", "input_tokens", "output_tokens")}
    return dict(total, by_prompt=by_prompt)


def write_reports(reports_dir, results, record):
    os.makedirs(reports_dir, exist_ok=True)
    lines = ["# Warnings report", "",
             "Cases and records a person should review. Generated by `python3 code/main.py`; identifiers are",
             "record and case ids only, never personal data.", ""]
    kinds = Counter()
    for r in results:
        for w in r.warnings:
            kinds[_kind(w)] += 1
    lines += ["## Summary", "", "| Warning | Count |", "|---|---|"]
    lines += [f"| {k} | {n} |" for k, n in kinds.most_common()]
    lines += ["", "## Per case", ""]
    for r in results:
        if r.warnings:
            lines.append(f"### {r.case_id} ({r.status})")
            lines += [f"- {w}" for w in r.warnings]
            lines.append("")
    with open(os.path.join(reports_dir, "warnings_report.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    usage = record["ai_usage"]
    rec = ["# Run record", "",
           "How the latest `output.csv` was made. Rerunning with the same data, code and saved AI answers",
           "gives a byte-identical `output.csv` (see `output_sha256`).", "",
           "| Item | Value |", "|---|---|"]
    for key in ("started_at", "dataset_fingerprint", "code_fingerprint", "requests", "output_sha256",
                "ai_provider", "ai_model", "ai_mode"):
        rec.append(f"| {key} | {record[key]} |")
    rec += ["", "## Prompts", "", "| Prompt | Version |", "|---|---|"]
    rec += [f"| {p.prompt_id} | {p.version} |" for p in record["prompts"]]
    rec += ["", "## Statuses", "", "| Status | Count |", "|---|---|"]
    rec += [f"| {s} | {n} |" for s, n in sorted(record["statuses"].items())]
    rec += ["", "## AI usage in this run", "",
            "| Prompt | Live calls | Cache hits | Input tokens | Output tokens |", "|---|---|---|---|---|"]
    rec += [f"| {name} | {u['live_calls']} | {u['cache_hits']} | {u['input_tokens']} | {u['output_tokens']} |"
            for name, u in sorted(usage["by_prompt"].items())]
    rec.append(f"| **total** | {usage['live_calls']} | {usage['cache_hits']} | {usage['input_tokens']} | {usage['output_tokens']} |")
    rec += ["", "Token counts of cache hits are those recorded when the answer was first made; a cache hit "
            "costs nothing in this run.", "", "## Evidence readers", "", "| Reader | Files |", "|---|---|"]
    rec += [f"| {name} | {n} |" for name, n in sorted(record["readers"].items())]
    with open(os.path.join(reports_dir, "run_record.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(rec) + "\n")


def _kind(warning):
    """A short category for the summary table (drops case and record ids)."""
    for marker in ("D-0", "RETENTION_ENDED", "human review", "UNKNOWN", "must be kept"):
        if marker in warning:
            start = warning.find(marker)
            return warning[start:start + 60] if marker != "D-0" else warning[warning.rfind("(D-"):].strip()
    return warning.split(":", 1)[-1].strip()[:60]


def main(argv=None):
    parser = argparse.ArgumentParser(description="Ghost Data Still Exists deletion-audit agent")
    parser.add_argument("--dataset", default=DATASET_DIR)
    parser.add_argument("--requests", help="requests CSV (default: <dataset>/deletion_requests.csv)")
    parser.add_argument("--output", default=os.path.join(REPO_ROOT, "output.csv"))
    parser.add_argument("--reports-dir", default=os.path.join(CODE_DIR, "evaluation"))
    parser.add_argument("--no-ai", action="store_true", help="no AI client: word check only, screenshots/PDFs unread")
    args = parser.parse_args(argv)
    requests_path = args.requests or os.path.join(args.dataset, "deletion_requests.csv")
    started = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    client, mode = None, "off (--no-ai)"
    settings = load_settings()
    if not args.no_ai:
        try:
            client = LLMClient(settings, LLM_CACHE_DIR)
            mode = "live calls allowed, cache first" if settings.api_key else "saved answers only (no LLM_API_KEY)"
        except LLMError as error:
            print(f"AI not available ({error}); continuing without it", file=sys.stderr)
            mode = "unavailable"

    agent = Agent(args.dataset, client)
    with open(requests_path, encoding="utf-8", newline="") as f:
        requests = sorted(csv.DictReader(f), key=lambda r: int(r["case_id"].split("_")[1]))  # D-006
    results = [agent.run_case(r) for r in requests]
    if agent.warnings:
        for r in results:
            r.warnings.extend(agent.warnings)

    rows = [[r.case_id, r.status, json.dumps(r.steps, separators=(",", ":"))] for r in results]
    temp = write_output(rows, args.output)
    problems = validate_output.validate(temp, requests_path, args.dataset)
    if problems:
        os.remove(temp)
        print("output.csv NOT written; format problems:", *problems[:20], sep="\n  ", file=sys.stderr)
        return 1
    os.replace(temp, args.output)

    with open(args.output, "rb") as f:
        output_sha = hashlib.sha256(f.read()).hexdigest()
    record = {
        "started_at": started,
        "dataset_fingerprint": fingerprint_files(files_under(args.dataset)),
        "code_fingerprint": fingerprint_files(files_under(CODE_DIR, (".py",))),
        "requests": len(requests),
        "output_sha256": output_sha,
        "ai_provider": settings.provider, "ai_model": settings.model, "ai_mode": mode,
        "prompts": [p for p in vars(prompts).values() if isinstance(p, Prompt)],
        "statuses": Counter(r.status for r in results),
        "ai_usage": ai_usage(client),
        "readers": Counter(agent.evidence.reader_by_file.values()),
    }
    write_reports(args.reports_dir, results, record)
    print(f"wrote {os.path.relpath(args.output, os.getcwd())}: {len(rows)} rows, {dict(record['statuses'])}; "
          f"AI live calls {record['ai_usage']['live_calls']}, cache hits {record['ai_usage']['cache_hits']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
